using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using HttpMachine.HeaderGen.Model;

namespace HttpMachine.HeaderGen;

/// <summary>Renders a <see cref="HeaderTable"/> as the KnownHeaders.g.cs source text.</summary>
/// <remarks>
/// <para>
/// The emitted file is deliberately free of tool versions, timestamps and machine names. The
/// output is committed to source control, so byte-stability is what makes the diff reviewable and
/// the CI drift check (see the build workflow) meaningful.
/// </para>
/// <para>
/// The emitted syntax stays at C# 7.3 level and never uses <c>null</c>, so the file compiles
/// unchanged in a project with any LangVersion and with nullable reference types either enabled or
/// disabled. That is why the generator never needs to inspect the compilation's parse options.
/// </para>
/// </remarks>
internal static class Emitter
{
    public const string HintName = "KnownHeaders.g.cs";

    private const string Namespace = "HttpMachine.Headers";

    public static string Emit(HeaderTable table)
    {
        var headers = table.Headers.AsImmutableArray();

        var enumMembers = new StringBuilder();
        var constants = new StringBuilder();
        var names = new StringBuilder();

        for (var i = 0; i < headers.Length; i++)
        {
            var header = headers[i];

            enumMembers.Append("        ").Append(header.EnumMember).Append(" = ").Append(i + 1).AppendLine(",");

            constants
                .Append("        /// <summary>The canonical spelling of the <c>").Append(Escape(header.Name))
                .AppendLine("</c> header.</summary>")
                .Append("        internal const string ").Append(header.EnumMember)
                .Append(" = \"").Append(Escape(header.Name)).AppendLine("\";");

            names.Append("            ").Append(header.EnumMember).AppendLine(",");
        }

        var matcher = EmitMatcher(headers);

        return $$"""
            //------------------------------------------------------------------------------
            // <auto-generated>
            //     This code was generated from headers/KnownHeaders.txt.
            //
            //     Changes to this file will be lost if the code is regenerated. Edit
            //     headers/KnownHeaders.txt and run tools/generate-known-headers.sh instead.
            // </auto-generated>
            //------------------------------------------------------------------------------

            using System;
            using System.Buffers.Binary;

            namespace {{Namespace}}
            {
                /// <summary>An HTTP header name recognised by <see cref="KnownHeaders.TryMatch"/>.</summary>
                internal enum KnownHeader
                {
                    /// <summary>Not a recognised header name.</summary>
                    None = 0,

            {{enumMembers.ToString().TrimEnd()}}
                }

                /// <summary>
                /// Maps a UTF-8 header name to a <see cref="KnownHeader"/> and a cached canonical string,
                /// without allocating.
                /// </summary>
                internal static class KnownHeaders
                {
            {{constants.ToString().TrimEnd()}}

                    /// <summary>
                    /// The canonical name of every known header, indexed by its <see cref="KnownHeader"/>
                    /// value. Index 0 corresponds to <see cref="KnownHeader.None"/> and is an empty string.
                    /// </summary>
                    internal static readonly string[] Names = new string[]
                    {
                        "",
            {{names.ToString().TrimEnd()}}
                    };

                    /// <summary>
                    /// Matches <paramref name="name"/> against the known header names, case-insensitively.
                    /// </summary>
                    /// <param name="name">
                    /// The header name as it appeared on the wire. Must contain only RFC 9110 token bytes;
                    /// the case folding below is only exact over that byte set.
                    /// </param>
                    /// <param name="header">The matched header, or <see cref="KnownHeader.None"/>.</param>
                    /// <param name="canonical">
                    /// The cached canonical spelling when the method returns <c>true</c>; otherwise an
                    /// empty string. Never null, so this file compiles under any nullable context.
                    /// </param>
                    /// <param name="exactCasing">
                    /// <c>true</c> when <paramref name="name"/> is byte-for-byte identical to
                    /// <paramref name="canonical"/>. Callers preserving the sender's casing use this to
                    /// decide whether the cached instance can stand in for the received bytes.
                    /// </param>
                    /// <returns><c>true</c> if the name is a known header.</returns>
                    internal static bool TryMatch(ReadOnlySpan<byte> name, out KnownHeader header, out string canonical, out bool exactCasing)
                    {
            {{matcher}}
                        header = KnownHeader.None;
                        canonical = "";
                        exactCasing = false;
                        return false;
                    }
                }
            }

            """;
    }

    private static string EmitMatcher(IReadOnlyList<HeaderSpec> headers)
    {
        if (headers.Count == 0)
        {
            return "            // No known headers are configured, so nothing can match.";
        }

        var sb = new StringBuilder();
        const string Indent = "            ";

        sb.Append(Indent).AppendLine("switch (name.Length)");
        sb.Append(Indent).AppendLine("{");

        var byLength = headers
            .GroupBy(h => Utf8Length(h.Name))
            .OrderBy(g => g.Key);

        var firstGroup = true;

        foreach (var lengthGroup in byLength)
        {
            var length = lengthGroup.Key;
            var reads = PlanReads(length);

            if (!firstGroup)
            {
                sb.AppendLine();
            }

            firstGroup = false;

            sb.Append(Indent).Append("    case ").Append(length).AppendLine(":");
            sb.Append(Indent).AppendLine("    {");

            for (var i = 0; i < reads.Count; i++)
            {
                sb.Append(Indent).Append("        ").AppendLine(reads[i].Declare(i));
            }

            // Candidates of the same length are separated by their first byte before any wide
            // comparison runs. Only ASCII letters fold into the letter range under "| 0x20", and
            // every header name starts with a letter, so the folded first byte is an exact
            // discriminant rather than a heuristic - the full comparison below still confirms.
            var byFirstByte = lengthGroup
                .GroupBy(h => (byte)(Utf8(h.Name)[0] | 0x20))
                .OrderBy(g => g.Key)
                .ToList();

            // Keyed on distinct first bytes, not on candidate count: several candidates sharing a
            // first byte would otherwise produce a switch with a single case.
            var useFirstByteSwitch = byFirstByte.Count > 1;

            if (useFirstByteSwitch)
            {
                sb.AppendLine();
                sb.Append(Indent).Append("        switch (").Append(FirstByteExpression(reads[0])).AppendLine(")");
                sb.Append(Indent).AppendLine("        {");
            }

            foreach (var firstByteGroup in byFirstByte)
            {
                var candidateIndent = Indent + (useFirstByteSwitch ? "                " : "        ");

                if (useFirstByteSwitch)
                {
                    sb.Append(Indent).Append("            case 0x").Append(firstByteGroup.Key.ToString("X2"))
                      .Append(": // '").Append((char)firstByteGroup.Key).AppendLine("'");
                }

                var first = true;

                foreach (var header in firstByteGroup.OrderBy(h => h.Name, StringComparer.Ordinal))
                {
                    if (!first)
                    {
                        sb.AppendLine();
                    }

                    first = false;
                    EmitCandidate(sb, candidateIndent, header, reads);
                }

                if (useFirstByteSwitch)
                {
                    sb.Append(candidateIndent).AppendLine("break;");
                }
            }

            if (useFirstByteSwitch)
            {
                sb.Append(Indent).AppendLine("        }");
            }

            sb.Append(Indent).AppendLine("    }");
            sb.Append(Indent).AppendLine("    break;");
        }

        sb.Append(Indent).AppendLine("}");
        sb.AppendLine();

        return sb.ToString().TrimEnd();
    }

    /// <summary>
    /// Emits the test for one candidate: whether the name matches ignoring case, and whether it was
    /// spelled canonically.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Both answers come out of a single XOR against the canonical bytes. <c>d = w ^ canonical</c>
    /// isolates exactly the bits that differ, and a case-insensitive match means "every differing
    /// bit is the 0x20 bit of a letter position" - so the match is <c>(d &amp; ~mask) == 0</c> and
    /// the exact-casing answer is <c>d == 0</c>, sharing the same XOR.
    /// </para>
    /// <para>
    /// This replaced a pair of independent comparison chains, one against the canonical bytes and
    /// one against the case-folded bytes. That form tested every candidate twice on the way to a
    /// miss and made the generated file about twice the size. The masking is exactly as precise:
    /// at a letter position the only bytes differing from the canonical one solely in the 0x20 bit
    /// are its own two case variants, and at a non-letter position <c>~mask</c> is <c>0xFF</c>, so
    /// the byte must match outright.
    /// </para>
    /// </remarks>
    private static void EmitCandidate(StringBuilder sb, string indent, HeaderSpec header, IReadOnlyList<Read> reads)
    {
        var bytes = Utf8(header.Name);
        var inner = indent + "    ";

        sb.Append(indent).Append("// ").AppendLine(header.Name);
        sb.Append(indent).AppendLine("{");

        var matchTerms = new List<string>();
        var exactTerms = new List<string>();
        var anyLetters = false;

        for (var i = 0; i < reads.Count; i++)
        {
            var read = reads[i];
            var exact = read.Pack(bytes, static b => b);
            var mask = read.Pack(bytes, static b => IsAsciiLetter(b) ? (byte)0x20 : (byte)0x00);

            sb.Append(inner).Append(read.DifferenceTypeName).Append(" d").Append(i)
              .Append(" = w").Append(i).Append(" ^ ").Append(read.Literal(exact)).AppendLine(";");

            // A chunk with no letters has nothing to fold, so its bytes must match outright and
            // masking would be a no-op.
            matchTerms.Add(mask == 0 ? $"d{i}" : $"(d{i} & {read.Literal(read.Complement(mask))})");
            exactTerms.Add($"d{i}");

            anyLetters |= mask != 0;
        }

        sb.Append(inner).Append("if ((").Append(string.Join(" | ", matchTerms)).AppendLine(") == 0)");
        sb.Append(inner).AppendLine("{");
        sb.Append(inner).Append("    header = KnownHeader.").Append(header.EnumMember).AppendLine(";");
        sb.Append(inner).Append("    canonical = ").Append(header.EnumMember).AppendLine(";");

        // With no letters anywhere, matching at all means the bytes were identical.
        sb.Append(inner).Append("    exactCasing = ")
          .Append(anyLetters ? $"({string.Join(" | ", exactTerms)}) == 0" : "true").AppendLine(";");

        sb.Append(inner).AppendLine("    return true;");
        sb.Append(inner).AppendLine("}");
        sb.Append(indent).AppendLine("}");
    }

    /// <summary>
    /// Extracts the first byte from the first read without a second bounds-checked load. A
    /// little-endian read places <c>name[0]</c> in the least significant byte on every
    /// architecture, so the cast is exact rather than platform-dependent.
    /// </summary>
    private static string FirstByteExpression(Read first) =>
        first.Width == 1 ? "w0 | 0x20" : "(byte)w0 | 0x20";

    /// <summary>
    /// Covers <paramref name="length"/> bytes with the fewest reads of width 8, 4, 2 or 1,
    /// overlapping the final read rather than stepping down through narrower widths. A 13-byte
    /// name costs two 8-byte comparisons (at 0 and at 5) instead of 8 + 4 + 1.
    /// </summary>
    private static IReadOnlyList<Read> PlanReads(int length)
    {
        var reads = new List<Read>();

        if (length >= 8)
        {
            var offset = 0;

            while (offset + 8 <= length)
            {
                reads.Add(new Read(offset, 8));
                offset += 8;
            }

            if (length % 8 != 0)
            {
                reads.Add(new Read(length - 8, 8));
            }
        }
        else if (length >= 4)
        {
            reads.Add(new Read(0, 4));

            if (length != 4)
            {
                reads.Add(new Read(length - 4, 4));
            }
        }
        else if (length >= 2)
        {
            reads.Add(new Read(0, 2));

            if (length != 2)
            {
                reads.Add(new Read(length - 2, 2));
            }
        }
        else
        {
            reads.Add(new Read(0, 1));
        }

        return reads;
    }

    private readonly struct Read
    {
        public Read(int offset, int width)
        {
            Offset = offset;
            Width = width;
        }

        public int Offset { get; }

        public int Width { get; }

        public string Declare(int index)
        {
            var slice = Offset == 0 ? "name" : $"name.Slice({Offset})";

            switch (Width)
            {
                case 8: return $"ulong w{index} = BinaryPrimitives.ReadUInt64LittleEndian({slice});";
                case 4: return $"uint w{index} = BinaryPrimitives.ReadUInt32LittleEndian({slice});";
                case 2: return $"ushort w{index} = BinaryPrimitives.ReadUInt16LittleEndian({slice});";
                default: return $"byte w{index} = name[{Offset}];";
            }
        }

        /// <summary>
        /// Packs this window's bytes little-endian, matching the read above. The generator produces
        /// the constants in a fixed byte order and the runtime reads in that same order, so the
        /// committed file is correct on big-endian hardware without regeneration.
        /// </summary>
        public ulong Pack(byte[] bytes, Func<byte, byte> select)
        {
            ulong value = 0;

            for (var i = 0; i < Width; i++)
            {
                value |= (ulong)select(bytes[Offset + i]) << (8 * i);
            }

            return value;
        }

        public string Literal(ulong value)
        {
            switch (Width)
            {
                case 8: return "0x" + value.ToString("X16") + "UL";
                case 4: return "0x" + value.ToString("X8") + "U";
                case 2: return "0x" + value.ToString("X4");
                default: return "0x" + value.ToString("X2");
            }
        }

        /// <summary>
        /// The type of <c>w ^ canonical</c>. Narrower reads promote to <c>int</c> under C#'s usual
        /// arithmetic conversions, so naming the promoted type here keeps the emitted code free of
        /// casts. Every read within one length group has the same width, so the difference terms
        /// are never mixed across types.
        /// </summary>
        public string DifferenceTypeName
        {
            get
            {
                switch (Width)
                {
                    case 8: return "ulong";
                    case 4: return "uint";
                    default: return "int";
                }
            }
        }

        /// <summary>Bitwise complement, truncated to this read's width.</summary>
        public ulong Complement(ulong mask) =>
            Width == 8 ? ~mask : ~mask & ((1UL << (8 * Width)) - 1);
    }

    private static bool IsAsciiLetter(byte b) => (b >= (byte)'a' && b <= (byte)'z') || (b >= (byte)'A' && b <= (byte)'Z');

    private static byte[] Utf8(string value) => Encoding.UTF8.GetBytes(value);

    private static int Utf8Length(string value) => Encoding.UTF8.GetByteCount(value);

    private static string Escape(string value) => value.Replace("\\", "\\\\").Replace("\"", "\\\"");
}
